"""ops/check_no_claude_attribution.py: what it flags, what it leaves alone, and that ci.yml runs it in every scope."""
from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SCRIPT = REPO / "ops" / "check_no_claude_attribution.py"
spec = importlib.util.spec_from_file_location("check_no_claude_attribution", SCRIPT)
chk = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
spec.loader.exec_module(chk)  # type: ignore[union-attr]

# Built from pieces so this file itself never contains a whole attribution line.
CO = "Co-Authored-" + "By"
MAIL = "noreply@" + "anthropic.com"


def test_flags_the_trailers_the_harness_adds() -> None:
    assert chk.find_attributions(f"fix\n\n{CO}: Claude Sonnet 5.5 <{MAIL}>")
    assert chk.find_attributions(f"{CO.lower()}: CLAUDE Opus 5.5 <x@y.z>")
    assert chk.find_attributions(f"{CO}: Someone <{MAIL}>")                       # the address alone is enough
    assert chk.find_attributions("\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)")
    assert chk.find_attributions("Generated with Claude Code")
    assert chk.find_attributions("Generated by Claude Code")
    assert chk.find_attributions("Created with Claude")
    assert chk.find_attributions("see https://claude.com/claude-code")


def test_leaves_other_text_alone() -> None:
    assert chk.find_attributions(f"{CO}: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>") == []
    assert chk.find_attributions(f"{CO}: Matt <t288matt@users.noreply.github.com>") == []
    assert chk.find_attributions(f"{CO}: Claudette Martin <c@example.com>") == []   # a human whose name starts with Claude
    assert chk.find_attributions("Untrack Claude working files and trim the docs index") == []
    assert chk.find_attributions("Docs: one-page card for the owner for when Claude is unavailable") == []


def _git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@example.com", *args], cwd=cwd, check=True, capture_output=True)


def _run(cwd: Path, **env: str) -> subprocess.CompletedProcess[str]:
    import os
    return subprocess.run([sys.executable, str(SCRIPT)], cwd=cwd, capture_output=True, text=True, env={**os.environ, **env})


def test_script_fails_on_a_dirty_commit_and_on_the_pr_text_and_passes_when_clean(tmp_path: Path) -> None:
    _git(tmp_path, "init", "-q")
    _git(tmp_path, "commit", "-q", "--allow-empty", "-m", "clean commit")
    assert _run(tmp_path).returncode == 0
    assert _run(tmp_path, PR_BODY=f"{CO}: Claude <{MAIL}>").returncode == 1
    assert _run(tmp_path, PR_TITLE="Generated with Claude Code").returncode == 1
    _git(tmp_path, "commit", "-q", "--allow-empty", "-m", f"dirty\n\n{CO}: Claude Sonnet 5.5 <{MAIL}>")
    r = _run(tmp_path)
    assert r.returncode == 1 and "commit" in r.stdout


def test_ci_runs_the_check_in_every_scope_and_ci_result_waits_for_it() -> None:
    ci = yaml.safe_load((REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8"))
    job = ci["jobs"]["quick-checks"]   # the check is a step of quick-checks since issue 340
    step = next(st for st in job["steps"] if str(st.get("name", "")).startswith("commit-attribution"))
    assert job["if"].replace(" ", "") == "${{!cancelled()}}"   # no scope condition: every scope, even if scope fails
    assert "scope" not in step["if"]                            # nor on the step
    assert step["run"] == "sh ops/run_checks.sh attribution"
    assert "ops/check_no_claude_attribution.py" in (REPO / "ops" / "run_checks.sh").read_text(encoding="utf-8")
    assert all("github.event.pull_request" not in st.get("run", "") for st in job["steps"])   # PR text goes through env only
    assert "quick-checks" in ci["jobs"]["ci-result"]["needs"]
